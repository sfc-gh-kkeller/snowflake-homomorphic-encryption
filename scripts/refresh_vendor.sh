#!/usr/bin/env bash
# Re-create vendor/Pyfhel-3.4.2 from upstream sources (documents exactly how the vendored copy was produced).
#
#   1. Pyfhel 3.4.2 sdist from PyPI (sha256 verified)
#   2. replace its bundled Microsoft SEAL 4.0.0 with SEAL v4.1.2 (commit verified)
#   3. disable SEAL's bundled zlib (SEAL_USE_ZLIB=OFF)
#
# See vendor/PATCHES.md for why. Requires: curl, git, tar, shasum (or sha256sum), sed.
set -euo pipefail

PYFHEL_VERSION=3.4.2
PYFHEL_SHA256=fa41664f8815b27f6347821f6363a7516fa84f50570816d8f292f2c22f88f88c
SEAL_TAG=v4.1.2
SEAL_COMMIT=119dc32e135cb89c1062076a69310d4413ebc824

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$ROOT/vendor/Pyfhel-$PYFHEL_VERSION}"   # optional: output directory (default: the vendored copy)
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

sha256() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }

echo "==> downloading Pyfhel $PYFHEL_VERSION sdist"
curl -fsSL -o "$WORK/pyfhel.tar.gz" "https://files.pythonhosted.org/packages/source/P/Pyfhel/Pyfhel-$PYFHEL_VERSION.tar.gz"
[ "$(sha256 "$WORK/pyfhel.tar.gz")" = "$PYFHEL_SHA256" ] || { echo "sha256 mismatch for Pyfhel sdist" >&2; exit 1; }
tar -xzf "$WORK/pyfhel.tar.gz" -C "$WORK"
SRC="$WORK/Pyfhel-$PYFHEL_VERSION"

echo "==> replacing bundled SEAL with $SEAL_TAG"
rm -rf "$SRC/Pyfhel/backend/SEAL"
git -c advice.detachedHead=false clone -q --depth 1 --branch "$SEAL_TAG" https://github.com/microsoft/SEAL.git "$SRC/Pyfhel/backend/SEAL"
[ "$(git -C "$SRC/Pyfhel/backend/SEAL" rev-parse HEAD)" = "$SEAL_COMMIT" ] || { echo "SEAL commit mismatch" >&2; exit 1; }
rm -rf "$SRC/Pyfhel/backend/SEAL/.git"

echo "==> SEAL_USE_ZLIB=OFF"
sed -i.bak -E "s/^([[:space:]]*SEAL_USE_ZLIB[[:space:]]*=[[:space:]]*)'ON'/\1'OFF'/" "$SRC/pyproject.toml"
rm -f "$SRC/pyproject.toml.bak"
grep -Eq "SEAL_USE_ZLIB[[:space:]]*=[[:space:]]*'OFF'" "$SRC/pyproject.toml" || { echo "zlib patch failed" >&2; exit 1; }

# generated by Cython at build time; not needed in the source tree
rm -rf "$SRC/Pyfhel.egg-info"

echo "==> installing into $DEST"
rm -rf "$DEST"
mkdir -p "$(dirname "$DEST")"
mv "$SRC" "$DEST"
echo "done. Rebuild the environment with: pixi reinstall Pyfhel"
